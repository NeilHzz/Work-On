def _set_font(rPr, ascii_f, ea_f):
    rFonts = OxmlElement("w:rFonts")
    rFonts.set(qn("w:ascii"),    ascii_f)
    rFonts.set(qn("w:hAnsi"),    ascii_f)
    rFonts.set(qn("w:eastAsia"), ea_f)
    rFonts.set(qn("w:cs"),       ascii_f)
    rPr.insert(0, rFonts)

def fmt(run, size=11, bold=False, italic=False, heading=False):
    run.font.size  = Pt(size)
    run.font.bold  = bold
    run.font.italic = italic
    rPr = run._r.get_or_add_rPr()
    if italic:
        _set_font(rPr, SCI_F, BODY)
    elif heading:
        _set_font(rPr, HEAD_F, HEAD_F)
    else:
        _set_font(rPr, BODY, BODY)

def spacing(p, before=0, after=120, line=24):
    pPr = p._p.get_or_add_pPr()
    e = OxmlElement("w:spacing")
    e.set(qn("w:before"),   str(before))
    e.set(qn("w:after"),    str(after))
    e.set(qn("w:line"),     str(line * 20))
    e.set(qn("w:lineRule"), "auto")
    pPr.append(e)

def para(text, bold=False, size=11, before=0, after=120,
         align=WD_ALIGN_PARAGRAPH.JUSTIFY, heading=False):
    p = doc.add_paragraph()
    p.alignment = align
    spacing(p, before=before, after=after)
    r = p.add_run(text)
    fmt(r, size=size, bold=bold, heading=heading)
    return p

def mixed(parts, before=0, after=120, align=WD_ALIGN_PARAGRAPH.JUSTIFY):
    p = doc.add_paragraph()
    p.alignment = align
    spacing(p, before=before, after=after)
    for text, bold, italic in parts:
        r = p.add_run(text)
        fmt(r, bold=bold, italic=italic)
    return p

def head(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    spacing(p, before=240, after=60)
    r = p.add_run(text)
    fmt(r, size=11, bold=True, heading=True)
    return p

def cite(p, numbers):
    """在段落末尾添加上标文献编号，如 cite(p, [1,2,3])"""
    r = p.add_run(",".join(str(n) for n in numbers))
    r.font.size = Pt(7)
    r.font.superscript = True
    rPr = r._r.get_or_add_rPr()
    _set_font(rPr, SCI_F, BODY)

